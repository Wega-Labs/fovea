#!/usr/bin/env python3
"""Regenerate the protocol reference page from the committed JSON Schema.

Field names, types, and required markers come from ``schema/fovea-protocol-v1.json``; event
descriptions come from the event dataclass docstrings, so neither can drift from the code.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, get_args

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fovea.events import FoveaEvent  # noqa: E402
from fovea.serialize import event_type_name  # noqa: E402

SCHEMA_PATH = ROOT / "schema" / "fovea-protocol-v1.json"
DESTINATION = ROOT / "docs" / "reference" / "protocol-messages.md"
COMMAND_PREFIX = "command_"
SCHEMA_URL = "https://github.com/Wega-Labs/fovea/blob/main/schema/fovea-protocol-v1.json"

# Command dataclasses have no docstrings; these mirror the stdin control words in the README.
COMMAND_DESCRIPTIONS = {
    "calibrate": "Restart calibration, optionally with a host-supplied target layout.",
    "test": "Start the calibrated gaze test, optionally with a host-supplied target layout.",
    "targets": "Replace the host-registered targets used for target-aware gaze.",
    "observe": "Report a host-confirmed gaze location for online calibration.",
    "pause": "Suppress event output without stopping local capture.",
    "resume": "Resume event output after `pause`.",
    "quit": "Close the source and exit cleanly.",
}


def event_descriptions() -> dict[str, str]:
    descriptions = {}
    for cls in get_args(FoveaEvent.__value__):
        doc = (cls.__doc__ or "").strip()
        descriptions[event_type_name(cls)] = " ".join(doc.split("\n\n")[0].split())
    return descriptions


def type_label(schema: dict[str, Any]) -> str:
    if "const" in schema:
        return f"`{json.dumps(schema['const'])}`"
    if "enum" in schema:
        return " \\| ".join(f"`{json.dumps(value)}`" for value in schema["enum"])
    if "anyOf" in schema:
        return " or ".join(type_label(option) for option in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"array of {type_label(schema.get('items', {}))}"
    return str(kind) if kind else "any"


def field_rows(schema: dict[str, Any], prefix: str = "") -> list[str]:
    rows = []
    required = set(schema.get("required", []))
    for name, field in schema.get("properties", {}).items():
        path = f"{prefix}{name}"
        rows.append(f"| `{path}` | {type_label(field)} | {'yes' if name in required else 'no'} |")
        items = field.get("items")
        if field.get("type") == "array" and isinstance(items, dict) and "properties" in items:
            rows.extend(field_rows(items, f"{path}[]."))
        elif field.get("type") == "object" and "properties" in field:
            rows.extend(field_rows(field, f"{path}."))
    return rows


def section(name: str, description: str, schema: dict[str, Any]) -> list[str]:
    lines = [f"### `{name}`", ""]
    if description:
        lines += [description, ""]
    lines += ["| Field | Type | Required |", "| --- | --- | --- |", *field_rows(schema), ""]
    return lines


def render() -> str:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    definitions: dict[str, Any] = schema["$defs"]
    events = event_descriptions()
    lines = [
        "# Protocol messages",
        "",
        "<!-- Generated by scripts/generate_protocol_reference.py from "
        "schema/fovea-protocol-v1.json. Do not edit by hand. -->",
        "",
        "Every event and control message in protocol major version 1, generated from the "
        f"checked-in [JSON Schema]({SCHEMA_URL}). See [Wire protocol](../protocol.md) for "
        "framing, the handshake, and compatibility rules. Consumers must ignore unknown fields "
        "and event types.",
        "",
        "## Events",
        "",
        "Written to stdout, one JSON object per line. `type` identifies the event.",
        "",
    ]
    for name, definition in definitions.items():
        if not name.startswith(COMMAND_PREFIX):
            lines += section(name, events.get(name, ""), definition)
    lines += [
        "## Control messages",
        "",
        "Written by the host to stdin, one JSON object per line. `cmd` identifies the command.",
        "",
    ]
    for name, definition in definitions.items():
        if name.startswith(COMMAND_PREFIX):
            command = name.removeprefix(COMMAND_PREFIX)
            lines += section(command, COMMAND_DESCRIPTIONS.get(command, ""), definition)
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    DESTINATION.parent.mkdir(parents=True, exist_ok=True)
    DESTINATION.write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
